export interface MasterCategoryDef {
  readonly name: string;
  readonly slug: string;
  readonly description: string;
  readonly sortOrder: number;
  readonly subcategories: readonly {
    readonly name: string;
    readonly slug: string;
    readonly description: string;
    readonly sortOrder: number;
  }[];
}

export interface MasterAttributeDef {
  readonly key: string;
  readonly label: string;
  readonly showOnCard: boolean;
  readonly sortOrder: number;
  readonly applicableCategorySlugs: readonly string[];
  readonly values: readonly {
    readonly value: string;
    readonly label: string;
    readonly sortOrder: number;
  }[];
}

export type ComponentPosition =
  | "FRONT"
  | "REAR"
  | "FRONT_LEFT"
  | "FRONT_RIGHT"
  | "REAR_LEFT"
  | "REAR_RIGHT"
  | "UNIVERSAL"
  | "UPPER"
  | "LOWER"
  | "IN_CABIN"
  | "ENGINE_BAY"
  | "UNDERCARRIAGE";

export interface MasterInspectionTargetDef {
  readonly targetKey: string;
  readonly label: string;
  readonly canonicalPartSlug: string;
  readonly defaultPosition: ComponentPosition;
}

export interface MasterInspectionCheckpointDef {
  readonly checkpointKey: string;
  readonly title: string;
  readonly systemSlug: string;
  readonly targets: readonly MasterInspectionTargetDef[];
}

export interface MasterCanonicalPartDef {
  readonly slug: string;
  readonly name: string;
  readonly systemSlug: string;
  readonly description: string;
  readonly supportedPositions?: readonly ComponentPosition[];
  readonly linkedServiceKeys: readonly string[];
}

export interface MasterItemDef {
  readonly sku: string;
  readonly name: string;
  readonly itemType: string;
  readonly categorySlug: string;
  readonly canonicalPartSlug?: string;
  readonly position?: ComponentPosition;
  readonly summary: string;
  readonly barcode: string;
  readonly supplier: string;
  readonly sellingPrice: string;
  readonly cost: string;
  readonly stockTracked: boolean;
  readonly initialStockQty: number; // positive = IN_STOCK, 0 = OUT_OF_STOCK
  readonly attributeValueKeys: readonly { readonly attributeKey: string; readonly value: string }[];
}

export interface MasterServiceDef {
  readonly serviceKey?: string; // Stable programmatic key, e.g. CAR_BATTERY_BMS_REPLACEMENT
  readonly itemKey: string;
  readonly displayName?: string; // Human localized name
  readonly category: string;
  readonly laborPrice: string;
  readonly unitPrice: string;
  readonly standardHours: number;
  readonly description: string;
  readonly linkedPartCategories: readonly string[];
  readonly canonicalPartSlug?: string;
  readonly applicablePositions?: readonly ComponentPosition[];
}

